export function getCharacterById(id: string): HanziCharacter {
  return HANZI_CHARACTERS.find((c) => c.id === id) ?? HANZI_CHARACTERS[0];
}

export function getCharactersForChapter(chapterId: string): HanziCharacter[] {
  const chapter = LEVEL_CHAPTERS.find((ch) => ch.id === chapterId);
  if (!chapter) return [];
  return chapter.characterIds
    .map((cid) => HANZI_CHARACTERS.find((c) => c.id === cid))
    .filter((c): c is HanziCharacter => Boolean(c));
}
